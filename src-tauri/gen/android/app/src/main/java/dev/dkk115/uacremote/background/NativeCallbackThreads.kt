package dev.dkk115.uacremote.background

import android.util.Log
import com.sun.jna.Callback
import com.sun.jna.CallbackThreadInitializer
import com.sun.jna.Native
import dev.dkk115.uacremote.nativecore.uniffiCallbackInterfaceNativePlatform
import java.lang.reflect.Modifier

/**
 * JNA's thread-detach policy for the generated callback vtable, nothing else.
 * JNA attaches a Rust-spawned ceremony thread to the VM when it enters a Kotlin
 * callback and detaches it again when that callback returns. A nested callback
 * therefore detached the thread while the outer Kotlin frames were still running
 * on it, and ART killed the process with "attempting to detach while still
 * running code". One initializer registered per generated callback keeps such a
 * thread attached for its whole life instead; JNA still detaches it when the
 * thread itself ends.
 *
 * This is not a capability, a key, a store or an authorization step. It reads
 * and writes no request, notification or key material, decides nothing about an
 * approval or a denial, adds no owner initialization step and changes no
 * generated interface. The only thing it changes is when JNA detaches a native
 * thread.
 */
internal object NativeCallbackThreads {
    // One shared policy for every vtable slot: daemon, so a pinned thread can
    // never hold the process open, and never detached by a returning callback.
    // Built on first registration, so loading this object touches no JNA class.
    private val keepAttachedPolicy: CallbackThreadInitializer by lazy {
        CallbackThreadInitializer(true /* daemon */, false /* detach */, "uac-native-callback")
    }

    /**
     * Pins the generated vtable after the generated contract check has built it
     * and before any ceremony thread can enter it. Returns how many callbacks
     * were pinned. Zero means the old detach policy still stands, which is a
     * crash risk and not a reason to refuse to open the owner.
     */
    internal fun pinGeneratedCallbacks(): Int {
        val pinned = try { pin(uniffiCallbackInterfaceNativePlatform.vtable) } catch (failure: Throwable) { unpinned(failure) }
        // Fixed-token startup diagnostic, never a payload. A count below the
        // vtable's own slots is the crash risk this object exists to remove.
        try { Log.i("UacBoot", "stage=CALLBACK_PIN pinned=$pinned") } catch (_: Throwable) { }
        return pinned
    }

    /**
     * The slots are enumerated instead of named, so a regenerated vtable with
     * new methods is pinned without editing this file. Repeating the call is
     * harmless and cheap: the same policy replaces itself. Nothing escapes,
     * including a missing JNA dispatch library, so the registration is a seam
     * the JVM unit test replaces.
     */
    internal fun pin(vtable: Any, register: (Callback) -> Unit = { keepAttached(it) }): Int {
        return try {
            var pinned = 0
            // The generated ByValue subclass inherits its slots, so every class
            // above it and below JNA's own Structure declares vtable fields.
            var type: Class<*>? = vtable.javaClass
            while (type != null && !type.name.startsWith("com.sun.jna.")) {
                for (field in type.declaredFields) {
                    if (Modifier.isStatic(field.modifiers)) continue
                    val slot = try {
                        field.isAccessible = true
                        field.get(vtable)
                    } catch (failure: Throwable) { unpinned(failure); continue }
                    if (slot !is Callback) continue
                    // Count out only the slot that refused, never the ones that
                    // are already pinned: the count must be what actually holds.
                    try { register(slot); pinned += 1 } catch (failure: Throwable) { unpinned(failure) }
                }
                type = type.superclass
            }
            pinned
        } catch (failure: Throwable) { unpinned(failure) }
    }

    /** Anything short of a dying VM leaves the callbacks unpinned rather than
     * escaping, because the caller has an owner to open either way. */
    private fun unpinned(failure: Throwable): Int {
        if (failure is VirtualMachineError || failure is ThreadDeath) throw failure
        return 0
    }

    private fun keepAttached(callback: Callback) = Native.setCallbackThreadInitializer(callback, keepAttachedPolicy)
}
