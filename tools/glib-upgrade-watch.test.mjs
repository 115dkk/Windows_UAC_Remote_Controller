import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import test from 'node:test';
import { decide, parseLock, probeManifest, pullingDeclarations, pullers, runWatch, vulnerable } from './glib-upgrade-watch.mjs';

const registry = 'registry+https://github.com/rust-lang/crates.io-index';

// controller-app -> tauri (vendored, no source) -> gtk -> glib 0.18.5, plus a
// second glib that is already patched and an unrelated serde edge.
const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "controller-app"
version = "1.11.0"
dependencies = [
 "serde",
 "tauri",
]

[[package]]
name = "glib"
version = "0.18.5"
source = "${registry}"

[[package]]
name = "glib"
version = "0.20.1"
source = "${registry}"

[[package]]
name = "gtk"
version = "0.18.2"
source = "${registry}"
dependencies = ["glib 0.18.5"]

[[package]]
name = "other"
version = "1.0.0"
source = "${registry}"
dependencies = [
 "glib 0.20.1",
]

[[package]]
name = "serde"
version = "1.0.228"
source = "${registry}"

[[package]]
name = "tauri"
version = "2.11.5"
dependencies = [
 "gtk",
 "other",
]
`;

const MEMBERS = [{
  name: 'controller-app',
  version: '1.11.0',
  dependencies: [
    { name: 'serde', path: null, uses_default_features: true, features: ['derive'] },
    { name: 'tauri', path: null, uses_default_features: false, features: ['x11', 'wry'] },
    { name: 'presentation-i18n', path: 'E:/repo/crates/presentation-i18n', uses_default_features: true, features: [] },
  ],
}];

test('the lock parser reads multi-line and single-line dependency lists', () => {
  const packages = parseLock(LOCK);
  assert.equal(packages.length, 7);
  assert.deepEqual(packages.find((pkg) => pkg.name === 'gtk').dependencies, ['glib 0.18.5']);
  assert.deepEqual(packages.find((pkg) => pkg.name === 'tauri'), { name: 'tauri', version: '2.11.5', source: null, dependencies: ['gtk', 'other'] });
  assert.throws(() => parseLock('[[package]]\nversion = "1.0.0"\n'), /without name or version/u);
});

test('only glib below 0.20 counts, and only its ancestors pull it in', () => {
  const packages = parseLock(LOCK);
  assert.deepEqual(vulnerable(packages).map((pkg) => pkg.version), ['0.18.5']);
  assert.deepEqual([...pullers(packages)].sort(), ['controller-app 1.11.0', 'glib 0.18.5', 'gtk 0.18.2', 'tauri 2.11.5']);
});

test('the probe declares the member\'s own tauri line, raised to the newest release', () => {
  const declarations = pullingDeclarations(MEMBERS, parseLock(LOCK));
  assert.deepEqual(declarations, [{ name: 'tauri', locked: '2.11.5', defaultFeatures: false, features: ['wry', 'x11'] }]);
  const manifest = probeManifest(declarations);
  assert.match(manifest, /^\[workspace\]$/mu);
  assert.match(manifest, /^tauri = \{ version = ">=2\.11\.5", default-features = false, features = \["wry", "x11"\] \}$/mu);
});

test('the verdict stands only while the newest releases still need the vulnerable glib', () => {
  const packages = parseLock(LOCK);
  const declarations = pullingDeclarations(MEMBERS, packages);
  const lockVulnerable = vulnerable(packages);
  const probe = (glib) => parseLock(`[[package]]\nname = "tauri"\nversion = "2.13.0"\nsource = "${registry}"\ndependencies = ["glib"]\n\n[[package]]\nname = "glib"\nversion = "${glib}"\nsource = "${registry}"\n`);

  const stands = decide({ lockVulnerable, declarations, probePackages: probe('0.18.5') });
  assert.equal(stands.ok, true);
  assert.match(stands.message, /newest releases \(tauri 2\.13\.0\) still resolve glib 0\.18\.5/u);

  const upgradable = decide({ lockVulnerable, declarations, probePackages: probe('0.21.0') });
  assert.equal(upgradable.ok, false);
  assert.match(upgradable.message, /An upgrade now clears RUSTSEC-2024-0429/u);

  const obsolete = decide({ lockVulnerable: [], declarations: [], probePackages: [] });
  assert.equal(obsolete.ok, false);
  assert.match(obsolete.message, /no longer holds glib < 0\.20/u);

  assert.equal(decide({ lockVulnerable, declarations: [], probePackages: [] }).ok, false);
});

test('a probe that cannot resolve fails instead of passing', () => {
  const calls = [];
  const spawn = (command, args) => {
    assert.equal(command, 'cargo');
    calls.push(args[0]);
    if (args[0] === 'metadata') return { status: 0, stdout: JSON.stringify({ packages: MEMBERS }), stderr: '' };
    return { status: 101, stdout: '', stderr: 'error: package `tauri` does not have feature `x11`' };
  };
  const read = (path) => {
    if (path.endsWith('Cargo.lock')) return LOCK;
    return readFileSync(path, 'utf8');
  };
  const verdict = runWatch({ cwd: join('E:', 'repo'), spawn, read });
  assert.deepEqual(calls, ['metadata', 'generate-lockfile']);
  assert.equal(verdict.ok, false);
  assert.match(verdict.message, /could not resolve the newest tauri/u);
  assert.match(verdict.message, /does not have feature `x11`/u);
});
