import { spawnSync } from 'node:child_process';
import {
  closeSync, constants, fstatSync, lstatSync, mkdirSync, openSync, opendirSync,
  readSync, realpathSync, writeFileSync,
} from 'node:fs';
import { posix, resolve, win32 } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ANDROID_API, CLANG_TARGET_FLAG, NDK_REVISION, RUST_TARGET,
  buildAndroidCompilerEnvironment, commandExitCode, ndkToolPaths,
  resolveAndroidNdk, selectNdkRoot,
} from './android-core-check.mjs';

const repository = fileURLToPath(new URL('../', import.meta.url));
const UNIFFI_VERSION = '0.32.0';
const ABI = 'arm64-v8a';
const LIBRARY = 'uac_android_controller';
const PACKAGE = 'dev.dkk115.uacremote.nativecore';
const MARKER = '.controller-uniffi.generated.json';
const CONFIG = 'uniffi-global.toml';
const KOTLIN_RELATIVE = `kotlin/dev/dkk115/uacremote/nativecore/${LIBRARY}.kt`;
const MAX_TREE_ENTRIES = 16;
const MAX_KOTLIN_BYTES = 4 * 1024 * 1024;
const MAX_HOST_OUTPUT = 16 * 1024;
const CONFIG_TEXT = `# Generated by build-android-bindings.mjs; UniFFI ${UNIFFI_VERSION} global config.\n[defaults.bindings.kotlin]\npackage_name = "${PACKAGE}"\ncdylib_name = "${LIBRARY}"\nandroid = true\ngenerate_immutable_records = true\nkotlin_target_version = "1.9.25"\nomit_checksums = false\n\n# Preserve these required values over any per-crate defaults.\n[crates.${LIBRARY}.bindings.kotlin]\npackage_name = "${PACKAGE}"\ncdylib_name = "${LIBRARY}"\nandroid = true\ngenerate_immutable_records = true\nkotlin_target_version = "1.9.25"\nomit_checksums = false\n`;
const ALLOWED_DIRECTORIES = new Set([
  'kotlin', 'kotlin/dev', 'kotlin/dev/dkk115', 'kotlin/dev/dkk115/uacremote',
  'kotlin/dev/dkk115/uacremote/nativecore',
]);
const ALLOWED_FILES = new Set([MARKER, CONFIG, KOTLIN_RELATIVE]);
const HELP = `Usage: node tools/build-android-bindings.mjs [--abi arm64-v8a] [--variant debug|release] [--dry-run]\n\nBuilds android-bindings with installed NDK ${NDK_REVISION}, API ${ANDROID_API}, then\nruns the matching UniFFI ${UNIFFI_VERSION} host generator on that actual Android .so.\nDefault: arm64-v8a, debug. Other ABIs are not implemented in this slice.\nCARGO_TARGET_DIR is honored; otherwise the workspace target directory is used.\nKotlin output is fixed under app/build/generated/controllerUniffi/<variant>/<abi>.\n--dry-run prints a plan only: no child process, installed-tool validation or writes.\n--help prints this text. No APK build, library copying, installation or deployment.\n`;

function pathsFor(platform) {
  if (platform === 'win32') return win32;
  if (platform === 'linux') return posix;
  throw new Error('Android binding tooling supports Windows and Linux hosts only.');
}

function environmentKey(environment, name, platform) {
  return platform === 'win32'
    ? Object.keys(environment).sort().find((key) => key.toUpperCase() === name.toUpperCase()) ?? name
    : name;
}

function environmentValue(environment, name, platform) {
  return environment[environmentKey(environment, name, platform)];
}

function absoluteLocalPath(value, label, platform) {
  const paths = pathsFor(platform);
  if (typeof value !== 'string' || value.length === 0 || value.length > 4096 || /[\u0000-\u001f\u007f]/.test(value)) {
    throw new Error(`${label} is not a supported local path.`);
  }
  const normalized = paths.normalize(value);
  if (platform === 'win32' ? !/^[a-z]:[\\/]/i.test(normalized) : !paths.isAbsolute(normalized)) {
    throw new Error(`${label} must be an absolute local path.`);
  }
  if (platform === 'win32' && normalized.slice(3).split(/[\\/]/).some((part) => part.includes(':') || /[. ]$/.test(part))) {
    throw new Error(`${label} must not use ambiguous Windows path components.`);
  }
  return normalized;
}

function contained(parent, path, platform) {
  const paths = pathsFor(platform);
  const relative = paths.relative(parent, path);
  return relative !== '' && relative !== '..' && !relative.startsWith(`..${paths.sep}`) && !paths.isAbsolute(relative);
}

export function parseArguments(argv) {
  if (!Array.isArray(argv) || argv.length > 8 || argv.some((arg) => typeof arg !== 'string' || arg.length > 128)) {
    throw new Error('Unsupported Android binding arguments. Use --help.');
  }
  if (argv.length === 1 && ['--help', '-h'].includes(argv[0])) {
    return Object.freeze({ help: true, dryRun: false, abi: ABI, variant: 'debug' });
  }
  const options = { help: false, dryRun: false, abi: ABI, variant: 'debug' };
  const seen = new Set();
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    if (seen.has(flag)) throw new Error('Duplicate Android binding option. Use --help.');
    seen.add(flag);
    if (flag === '--dry-run') { options.dryRun = true; continue; }
    if (flag !== '--abi' && flag !== '--variant') throw new Error('Unsupported Android binding option. Use --help.');
    const value = argv[++index];
    if (flag === '--abi') {
      if (value !== ABI) throw new Error('Only the arm64-v8a ABI is implemented; no other ABI was built.');
      options.abi = value;
    } else {
      if (!['debug', 'release'].includes(value)) throw new Error('Variant must be debug or release.');
      options.variant = value;
    }
  }
  return Object.freeze(options);
}

/** Bounded rustc metadata, not a guessed host-tuple artifact directory. */
export function parseRustHost(output, platform) {
  pathsFor(platform);
  if (typeof output !== 'string' || output.length > MAX_HOST_OUTPUT) throw new Error('Rust host metadata is unavailable or oversized.');
  const lines = output.split(/\r?\n/).filter((line) => line.startsWith('host:'));
  const host = lines.length === 1 ? /^host: ([a-z0-9_]+(?:-[a-z0-9_]+){2,4})$/.exec(lines[0])?.[1] : null;
  if (!host) throw new Error('Rust host metadata must contain one supported host target.');
  if (!host.startsWith('x86_64-') || (platform === 'win32'
    ? !/-windows-(?:msvc|gnu|gnullvm)$/.test(host) : !/-linux-(?:gnu|musl)$/.test(host))) {
    throw new Error('The installed NDK host toolchain requires a matching x86_64 Windows or Linux Rust host.');
  }
  return host;
}

/** Pure argument/environment/path planning. No filesystem access or subprocess. */
export function createBuildPlan({ options, environment, platform, cwd, ndk, hostTarget = null }) {
  const paths = pathsFor(platform);
  // Revalidate exported-call inputs as well as the CLI path.
  if (options?.abi !== ABI || !['debug', 'release'].includes(options?.variant)) throw new Error('Unsupported Android binding plan.');
  cwd = absoluteLocalPath(cwd, 'Workspace', platform);
  const configured = environmentValue(environment, 'CARGO_TARGET_DIR', platform);
  let targetDirectory;
  if (configured === undefined || configured === '') targetDirectory = paths.join(cwd, 'target');
  else {
    if (typeof configured !== 'string' || /[\u0000-\u001f\u007f]/.test(configured) || configured.length > 4096) {
      throw new Error('CARGO_TARGET_DIR is not a supported local path.');
    }
    if (!paths.isAbsolute(configured) && configured.split(/[\\/]/).includes('..')) {
      throw new Error('Relative CARGO_TARGET_DIR must stay inside the workspace.');
    }
    if (platform === 'win32' && (/^[a-z]:(?![\\/])/i.test(configured) || /^[\\/]/.test(configured))) {
      throw new Error('CARGO_TARGET_DIR must not use a drive-relative or network path.');
    }
    targetDirectory = absoluteLocalPath(paths.resolve(cwd, configured), 'CARGO_TARGET_DIR', platform);
  }
  if (paths.relative(paths.parse(targetDirectory).root, targetDirectory) === ''
      || paths.relative(cwd, targetDirectory) === '' || contained(targetDirectory, cwd, platform)) {
    throw new Error('CARGO_TARGET_DIR must be a dedicated build directory, not a root or workspace ancestor.');
  }
  if (ndk?.revision !== NDK_REVISION) throw new Error('The build plan requires the pinned NDK revision.');
  const derivedTools = ndkToolPaths(ndk.root, platform);
  if (ndk.clang !== derivedTools.clang || ndk.ar !== derivedTools.ar) throw new Error('NDK tools must match the selected pinned toolchain layout.');
  const rustc = environmentValue(environment, 'RUSTC', platform) || 'rustc';
  if (typeof rustc !== 'string' || rustc.length > 4096 || /[\u0000-\u001f\u007f]/.test(rustc)) throw new Error('Configured RUSTC must be one executable path, without control characters.');
  const nativeEnvironment = buildAndroidCompilerEnvironment(environment, ndk, platform);
  const linkerKey = environmentKey(environment, 'CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER', platform);
  nativeEnvironment[linkerKey] = ndk.clang;
  const appDirectory = paths.join(cwd, 'src-tauri', 'gen', 'android', 'app');
  const generatedParent = paths.join(appDirectory, 'build', 'generated', 'controllerUniffi');
  const output = paths.join(generatedParent, options.variant, options.abi);
  if (!contained(generatedParent, output, platform)) throw new Error('Generated output escaped its fixed parent.');
  const library = paths.join(targetDirectory, RUST_TARGET, options.variant, `lib${LIBRARY}.so`);
  const config = paths.join(output, CONFIG);
  const kotlinDirectory = paths.join(output, 'kotlin');
  const markerText = `${JSON.stringify({ schemaVersion: 1, tool: 'controller-uniffi-bindgen', uniffi: UNIFFI_VERSION, library: LIBRARY, package: PACKAGE, abi: options.abi, variant: options.variant })}\n`;
  if (hostTarget !== null) parseRustHost(`host: ${hostTarget}\n`, platform);
  return {
    abi: options.abi, variant: options.variant, platform, cwd, targetDirectory,
    appDirectory, generatedParent, output, library, config, kotlinDirectory,
    kotlinFile: paths.join(output, ...KOTLIN_RELATIVE.split('/')),
    marker: paths.join(output, MARKER), markerText, configText: CONFIG_TEXT,
    generatorArtifact: hostTarget === null ? null : paths.join(targetDirectory, hostTarget, 'debug', `controller-uniffi-bindgen${platform === 'win32' ? '.exe' : ''}`),
    probe: { command: rustc, args: ['-vV'], environment: { ...environment } },
    build: {
      command: 'cargo', environment: nativeEnvironment,
      args: ['rustc', '--locked', '--package', 'android-bindings', '--lib', '--target', RUST_TARGET,
        '--manifest-path', paths.join(cwd, 'Cargo.toml'), '--target-dir', targetDirectory,
        '--profile', options.variant === 'debug' ? 'dev' : 'release', '--',
        '-C', `linker=${ndk.clang}`, '-C', `link-arg=${CLANG_TARGET_FLAG}`],
    },
    generate: {
      command: 'cargo', environment: { ...environment },
      args: ['run', '--locked', '--package', 'controller-uniffi-bindgen', '--target', 'host-tuple',
        '--manifest-path', paths.join(cwd, 'Cargo.toml'), '--target-dir', targetDirectory,
        '--profile', 'dev', '--', 'generate', library, '--language', 'kotlin',
        '--config', config, '--out-dir', kotlinDirectory, '--no-format'],
    },
  };
}

/** Pure validation of bounded filesystem metadata; no file contents except two small owned text files. */
export function validateGeneratedEntries(entries, markerText) {
  if (!Array.isArray(entries) || entries.length > MAX_TREE_ENTRIES) throw new Error('Generated output exceeds its fixed tree bound.');
  const seen = new Set();
  for (const entry of entries) {
    if (seen.has(entry.path)) throw new Error('Generated output has duplicate entries.');
    seen.add(entry.path);
    if (entry.kind === 'directory' && ALLOWED_DIRECTORIES.has(entry.path)) continue;
    if (entry.kind !== 'file' || !ALLOWED_FILES.has(entry.path) || entry.links !== 1) {
      throw new Error('Generated output contains an unknown, linked, or nonregular entry; nothing was cleaned.');
    }
    const maximum = entry.path === KOTLIN_RELATIVE ? MAX_KOTLIN_BYTES : 4096;
    if (!Number.isSafeInteger(entry.size) || entry.size < 0 || entry.size > maximum) throw new Error('Generated output file exceeds its bound.');
    if (entry.path === MARKER && entry.text !== markerText) throw new Error('Generated output ownership marker does not match this build.');
    if (entry.path === CONFIG && entry.text !== CONFIG_TEXT) throw new Error('Generated configuration changed; inspect it before rebuilding.');
  }
  if (entries.length !== 0 && !seen.has(MARKER)) throw new Error('Existing output has no matching generated ownership marker.');
}

function safeDirectory(path, platform, create = false) {
  const paths = pathsFor(platform);
  const parsed = paths.parse(path);
  let current = parsed.root;
  for (const part of paths.relative(parsed.root, path).split(paths.sep).filter(Boolean)) {
    current = paths.join(current, part);
    let metadata;
    try { metadata = lstatSync(current); }
    catch (error) {
      if (!create || error.code !== 'ENOENT') throw new Error('A required build directory is unavailable.');
      mkdirSync(current);
      metadata = lstatSync(current);
    }
    if (!metadata.isDirectory() || metadata.isSymbolicLink() || paths.relative(current, realpathSync(current)) !== '') {
      throw new Error('Build directory aliases, symlinks and non-directory entries are not supported.');
    }
  }
}

function smallText(path, maximum) {
  const fd = openSync(path, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
  try {
    const metadata = fstatSync(fd);
    if (!metadata.isFile() || metadata.nlink !== 1 || metadata.size > maximum) throw new Error('Generated metadata is not a bounded regular file.');
    const buffer = Buffer.alloc(maximum + 1);
    let used = 0;
    while (used < buffer.length) {
      const count = readSync(fd, buffer, used, buffer.length - used, used);
      if (count === 0) break;
      used += count;
    }
    if (used > maximum) throw new Error('Generated metadata exceeds its byte bound.');
    return buffer.subarray(0, used).toString('utf8');
  } finally { closeSync(fd); }
}

function outputEntries(plan) {
  const paths = pathsFor(plan.platform);
  const entries = [];
  const visit = (directory, relative) => {
    const handle = opendirSync(directory);
    try {
      for (let entry = handle.readSync(); entry !== null; entry = handle.readSync()) {
        if (entries.length >= MAX_TREE_ENTRIES) throw new Error('Generated output exceeds its fixed tree bound.');
        const name = relative ? `${relative}/${entry.name}` : entry.name;
        if (!ALLOWED_DIRECTORIES.has(name) && !ALLOWED_FILES.has(name)) throw new Error('Generated output contains unknown files; nothing was cleaned.');
        const absolute = paths.join(directory, entry.name);
        const metadata = lstatSync(absolute);
        const kind = metadata.isSymbolicLink() ? 'link' : metadata.isDirectory() ? 'directory' : metadata.isFile() ? 'file' : 'other';
        if ((kind === 'directory' && !ALLOWED_DIRECTORIES.has(name))
          || (kind !== 'directory' && kind !== 'file')) throw new Error('Generated output contains a linked or nonregular entry.');
        const item = { path: name, kind, links: metadata.nlink, size: metadata.size };
        if (kind === 'file' && [MARKER, CONFIG].includes(name)) item.text = smallText(absolute, 4096);
        entries.push(item);
        if (kind === 'directory') visit(absolute, name);
      }
    } finally { handle.closeSync(); }
  };
  visit(plan.output, '');
  validateGeneratedEntries(entries, plan.markerText);
  return entries;
}

function prepareOutput(plan) {
  safeDirectory(plan.appDirectory, plan.platform);
  safeDirectory(plan.output, plan.platform, true);
  const entries = outputEntries(plan);
  if (entries.length === 0) writeFileSync(plan.marker, plan.markerText, { flag: 'wx', mode: 0o600 });
  // Existing exact marker + fixed whitelist is mandatory before any overwrite.
  outputEntries(plan);
  if (!entries.some((entry) => entry.path === CONFIG)) writeFileSync(plan.config, CONFIG_TEXT, { flag: 'wx', mode: 0o600 });
  safeDirectory(plan.kotlinDirectory, plan.platform, true);
  safeDirectory(plan.targetDirectory, plan.platform, true);
  outputEntries(plan);
}

function requireLibrary(plan) {
  const paths = pathsFor(plan.platform);
  safeDirectory(paths.dirname(plan.library), plan.platform);
  const metadata = lstatSync(plan.library);
  if (!metadata.isFile() || metadata.isSymbolicLink() || metadata.size === 0
      || paths.relative(plan.library, realpathSync(plan.library)) !== '') {
    throw new Error('The successful Android build did not produce the expected regular cdylib.');
  }
  // Cargo normally hard-links the top-level cdylib to its exact deps artifact.
  // This is a read-only input, not a generated output that we overwrite. Permit
  // only that observed two-name pair; do not copy it or relax output-file rules.
  if (metadata.nlink !== 1) {
    const deps = paths.join(paths.dirname(plan.library), 'deps');
    safeDirectory(deps, plan.platform);
    const peerPath = paths.join(deps, paths.basename(plan.library));
    const peer = lstatSync(peerPath, { bigint: true });
    const original = lstatSync(plan.library, { bigint: true });
    if (!peer.isFile() || peer.isSymbolicLink() || original.nlink !== 2n || peer.nlink !== 2n
        || original.dev !== peer.dev || original.ino !== peer.ino) {
      throw new Error('The built cdylib has an unexpected hard-link relationship.');
    }
  }
  // UniFFI parses this exact built library. No host .dll, stale-path fallback,
  // synthetic library, checksum omission, or copying into Tauri is attempted.
}

function requireGenerated(plan) {
  const entries = outputEntries(plan);
  if (!entries.some((entry) => entry.path === KOTLIN_RELATIVE && entry.kind === 'file' && entry.size > 0)) {
    throw new Error('The generator did not produce the expected Kotlin bindings.');
  }
}

const nativeFiles = Object.freeze({ prepareOutput, requireLibrary, requireGenerated });

function displayPlan(plan, stdout) {
  stdout.write(`Android bindings plan: ${plan.abi}, ${plan.variant}, NDK ${NDK_REVISION}, API ${ANDROID_API}; not an APK/device check.\n`);
  for (const step of [plan.probe, plan.build, plan.generate]) stdout.write(`${step.command} ${JSON.stringify(step.args)}\n`);
  if (plan.generatorArtifact === null) stdout.write('Host artifact directory will be resolved from checked rustc -vV output on the actual run.\n');
}

export function runAndroidBindings({
  args = process.argv.slice(2), environment = process.env, platform = process.platform,
  cwd = repository, spawn = spawnSync, ndkResolver = resolveAndroidNdk,
  files = nativeFiles, stdout = process.stdout, stderr = process.stderr,
} = {}) {
  const options = parseArguments(args);
  if (options.help) { stdout.write(HELP); return 0; }
  if (options.dryRun) {
    const selected = selectNdkRoot(environment, platform);
    const ndk = { ...ndkToolPaths(selected.root, platform), revision: NDK_REVISION };
    displayPlan(createBuildPlan({ options, environment, platform, cwd, ndk }), stdout);
    stdout.write('Dry run only: installed tools, compiler output and generated files were not verified.\n');
    return 0;
  }
  const ndk = ndkResolver(environment, platform);
  const preliminary = createBuildPlan({ options, environment, platform, cwd, ndk });
  const invoke = (step, label, capture = false) => {
    let result;
    try {
      result = spawn(step.command, step.args, {
        cwd: preliminary.cwd, env: step.environment, shell: false, windowsHide: true,
        stdio: capture ? ['ignore', 'pipe', 'inherit'] : 'inherit',
        encoding: capture ? 'utf8' : undefined, maxBuffer: capture ? MAX_HOST_OUTPUT : undefined,
        timeout: capture ? 10_000 : 900_000,
      }) ?? { status: null };
    } catch { result = { status: null, error: true }; }
    const code = commandExitCode(result);
    if (code !== 0) stderr.write(`Android binding ${label} failed (exit ${code}); later stages were not run.\n`);
    return { result, code };
  };
  const host = invoke(preliminary.probe, 'host discovery', true);
  if (host.code !== 0) return host.code;
  const hostTarget = parseRustHost(host.result.stdout, platform);
  const plan = createBuildPlan({ options, environment, platform, cwd, ndk, hostTarget });
  files.prepareOutput(plan);
  displayPlan(plan, stdout);
  const build = invoke(plan.build, 'native build');
  if (build.code !== 0) return build.code;
  files.requireLibrary(plan);
  const generate = invoke(plan.generate, 'generation');
  if (generate.code !== 0) return generate.code;
  files.requireGenerated(plan);
  stdout.write('Android arm64 cdylib and matching Kotlin generation completed. No APK packaging or device behavior was validated.\n');
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = runAndroidBindings(); }
  catch {
    process.stderr.write('Android binding setup or artifact verification failed. Inspect the selected local build paths and pinned toolchain; no fallback was attempted.\n');
    process.exitCode = 1;
  }
}
